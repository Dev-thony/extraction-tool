def read_text(path):
    return path.read_text(encoding='utf-8') if path.exists() else ''

def backup(path):
    BACKUPS.mkdir(exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')
    rel = path.relative_to(ROOT)
    out = BACKUPS / stamp / rel
    out.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(path, out)
    return out

def audit():
    targets = list((ROOT/'apps').rglob('*.css')) + list((ROOT/'apps').rglob('*.tsx'))
    findings=[]
    patterns = [
        ('fixed-width', re.compile(r'(?<!max-)width\s*:\s*(?:[2-9]\d\d|\d{4,})px')),
        ('fixed-min-width', re.compile(r'min-width\s*:\s*(?:[3-9]\d\d|\d{4,})px')),
        ('absolute-position', re.compile(r'position\s*:\s*absolute')),
        ('nowrap', re.compile(r'white-space\s*:\s*nowrap')),
        ('viewport-width', re.compile(r'(?:width|min-width)\s*:\s*100vw')),
        ('large-grid-track', re.compile(r'(?:minmax|grid-template-columns)[^;]*(?:3\d\d|4\d\d|5\d\d)px')),
    ]
    for p in targets:
        text=read_text(p)
        for name, pat in patterns:
            for m in pat.finditer(text):
                line=text.count('\n',0,m.start())+1
                findings.append({'file':str(p.relative_to(ROOT)),'line':line,'rule':name,'snippet':text.splitlines()[line-1].strip()[:240]})
    report={'generatedAt':datetime.now(timezone.utc).isoformat(),'findings':findings,'count':len(findings)}
    REPORTS.mkdir(exist_ok=True)
    (REPORTS/'static-audit.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(f"Static audit: {len(findings)} findings -> .uiux-reports/static-audit.json")
    return report

def research():
    REPORTS.mkdir(exist_ok=True)
    result={'generatedAt':datetime.now(timezone.utc).isoformat(),'sources':{}}
    for title,url in STANDARDS.items():
        try:
            req=urllib.request.Request(url,headers={'User-Agent':'DataExtractor-UIUX-Research/1.0'})
            with urllib.request.urlopen(req,timeout=12) as r:
                body=r.read(20000).decode('utf-8','ignore')
            result['sources'][title]={'url':url,'status':'ok','bytesSampled':len(body)}
        except Exception as exc:
            result['sources'][title]={'url':url,'status':'unavailable','error':str(exc)}
    (REPORTS/'standards.json').write_text(json.dumps(result,indent=2),encoding='utf-8')
    print('Standards manifest -> .uiux-reports/standards.json')
    return result

def apply_changes():
    admin_css=ROOT/'apps/admin/app/globals.css'
    extractor_css=ROOT/'apps/extractor/app/globals.css'
    sidebar=ROOT/'apps/admin/components/admin-sidebar.tsx'
    changed=[]
    for path in [admin_css, extractor_css, sidebar]:
        if not path.exists():
            print(f'SKIP missing: {path.relative_to(ROOT)}')
            continue
        backup(path)
    # CSS layer is appended/replaced safely.
    for path in [admin_css, extractor_css]:
        if not path.exists(): continue
        old=read_text(path)
        start=old.find('/* UIUX_ENGINE_RESPONSIVE_LAYER_START')
        end=old.find('/* UIUX_ENGINE_RESPONSIVE_LAYER_END */')
        if start >= 0 and end >= 0:
            new=old[:start]+CSS_LAYER.strip()+old[end+len('/* UIUX_ENGINE_RESPONSIVE_LAYER_END */'):]
        else:
            new=old.rstrip()+"\n\n"+CSS_LAYER.strip()+"\n"
        path.write_text(new,encoding='utf-8'); changed.append(str(path.relative_to(ROOT)))
    if sidebar.exists():
        old=read_text(sidebar)
        if '/*__UIUX_ENGINE_SIDEBAR__*/' not in old:
            sidebar.write_text(SIDEBAR_COMPONENT,encoding='utf-8'); changed.append(str(sidebar.relative_to(ROOT)))
    print('Applied:', ', '.join(changed) if changed else 'nothing')
    return changed

def run_visual():
    runner=ROOT/'tools'/'uiux_engine_playwright.mjs'
    runner.write_text(PLAYWRIGHT_RUNNER,encoding='utf-8')
    env=os.environ.copy()
    env['UIUX_ROOT']=str(ROOT)
    try:
        p=subprocess.run(['node',str(runner)],cwd=ROOT,env=env,text=True,capture_output=True,timeout=300)
        print(p.stdout)
        if p.returncode: print(p.stderr,file=sys.stderr)
        return p.returncode==0
    except FileNotFoundError:
        print('Node is not installed; visual audit skipped.')
        return False

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('command',choices=['audit','research','visual','apply','all'])
    args=ap.parse_args()
    if args.command=='audit': audit()
    elif args.command=='research': research()
    elif args.command=='visual': run_visual()
    elif args.command=='apply': apply_changes()
    else:
        research(); audit(); run_visual(); apply_changes(); audit(); run_visual()

PLAYWRIGHT_RUNNER = r'''import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';

const root = process.env.UIUX_ROOT || process.cwd();
const out = path.join(root, '.uiux-reports', 'visual');
fs.mkdirSync(out, { recursive: true });
const base = process.env.UIUX_BASE_URL || 'http://localhost:3000';
const viewports = [
  [320,800],[375,812],[390,844],[414,896],[768,1024],[820,1180],
  [1024,768],[1280,720],[1440,900],[1920,1080]
];
const paths = ['/', '/records', '/batches'];
const extractor = process.env.UIUX_EXTRACTOR_URL || base;
const admin = process.env.UIUX_ADMIN_URL || 'http://localhost:3001';
const adminPaths = process.env.UIUX_SKIP_ADMIN === '1' ? [] : ['/login','/','/records','/batches'];
const results=[];

async function loginIfPossible(page) {
  const email = process.env.UIUX_ADMIN_EMAIL || process.env.ADMIN_EMAIL;
  const password = process.env.UIUX_ADMIN_PASSWORD || process.env.ADMIN_PASSWORD;
  if (!email || !password) return false;
  const emailInput = page.locator('input[type="email"], input[name="email"]').first();
  const passInput = page.locator('input[type="password"], input[name="password"]').first();
  if (await emailInput.count() && await passInput.count()) {
    await emailInput.fill(email); await passInput.fill(password);
    await page.locator('button[type="submit"]').first().click();
    await page.waitForLoadState('networkidle').catch(()=>{});
    return true;
  }
  return false;
}

async function testPage(browser, baseUrl, route, w, h, needsLogin=false) {
  const context=await browser.newContext({ viewport:{width:w,height:h}, deviceScaleFactor:1 });
  const page=await context.newPage();
  const consoleErrors=[]; const failed=[];
  page.on('console', m => { if (m.type()==='error') consoleErrors.push(m.text()); });
  page.on('requestfailed', r => failed.push(r.url()));
  const started=Date.now();
  let error=null;
  try {
    await page.goto(baseUrl+route,{waitUntil:'networkidle',timeout:30000});
    if (needsLogin && route !== '/login') {
      const logged = await loginIfPossible(page);
      if (logged) await page.goto(baseUrl+route,{waitUntil:'networkidle',timeout:30000});
    }
    await page.screenshot({path:path.join(out, `${safe(route)}-${w}x${h}.png`), fullPage:true});
    const metrics=await page.evaluate(() => {
      const els=[...document.querySelectorAll('body *')];
      const outside=[];
      for (const el of els) {
        const r=el.getBoundingClientRect();
        if (r.width>0 && (r.right > innerWidth+2 || r.left < -2)) outside.push({tag:el.tagName,cls:typeof el.className==='string'?el.className:'',left:r.left,right:r.right,width:r.width});
      }
      const small=[];
      for (const el of els) {
        if (!(el instanceof HTMLElement)) continue;
        if (!['A','BUTTON','INPUT','SELECT','TEXTAREA','SUMMARY'].includes(el.tagName)) continue;
        const r=el.getBoundingClientRect();
        if (r.width>0 && (r.width<24 || r.height<24)) small.push({tag:el.tagName,text:(el.innerText||el.getAttribute('aria-label')||'').trim().slice(0,80),width:r.width,height:r.height});
      }
      return {scrollWidth:document.documentElement.scrollWidth,clientWidth:document.documentElement.clientWidth,overflow:document.documentElement.scrollWidth>document.documentElement.clientWidth+1,outside:outside.slice(0,25),small:small.slice(0,25)};
    });
    results.push({route,width:w,height:h,durationMs:Date.now()-started,consoleErrors,failed,metrics});
  } catch(e) { error=String(e); results.push({route,width:w,height:h,error,consoleErrors,failed}); }
  await context.close();
}
function safe(s){return s.replace(/[^a-z0-9]+/gi,'-').replace(/^-|-$/g,'')||'home';}

const browser=await chromium.launch({headless:true});
for (const [w,h] of viewports) {
  for (const r of paths) await testPage(browser,extractor,r,w,h,false);
  for (const r of adminPaths) await testPage(browser,admin,r,w,h,r !== '/login');
}
await browser.close();
const summary={generatedAt:new Date().toISOString(),base,results};
fs.writeFileSync(path.join(out,'summary.json'),JSON.stringify(summary,null,2));
const bad=results.filter(x=>x.error || x.metrics?.overflow || x.consoleErrors?.length || x.failed?.length);
console.log(`Visual audit complete: ${results.length} checks, ${bad.length} flagged. Reports: .uiux-reports/visual`);
process.exit(bad.length ? 2 : 0);
'''

