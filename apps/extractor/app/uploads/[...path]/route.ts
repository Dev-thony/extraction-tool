import { NextResponse } from 'next/server';
import { readFile } from 'node:fs/promises';
import path from 'node:path';

const STORAGE_DIR = path.resolve(process.cwd(), process.env.LOCAL_STORAGE_DIR || 'storage/uploads');

const CONTENT_TYPES: Record<string, string> = {
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
  '.webp': 'image/webp',
  '.gif': 'image/gif',
};

export async function GET(
  _request: Request,
  context: {
    params: Promise<{
      path: string[];
    }>;
  },
) {
  try {
    const { path: segments } = await context.params;

    if (!segments || segments.length !== 1) {
      return NextResponse.json({ error: 'Invalid file path.' }, { status: 400 });
    }

    const filename = segments?.[0];

    if (!filename) {
      return NextResponse.json({ error: 'Invalid file path.' }, { status: 400 });
    }

    /*
     * Uploaded keys are generated by LocalStorageProvider as UUID + extension.
     * Reject path traversal rather than allowing arbitrary filesystem access.
     */
    if (filename.includes('/') || filename.includes('\\') || filename.includes('..')) {
      return NextResponse.json({ error: 'Invalid file path.' }, { status: 400 });
    }

    const filePath = path.resolve(STORAGE_DIR, filename);

    /*
     * Make absolutely sure the resolved path remains inside STORAGE_DIR.
     */
    if (filePath !== STORAGE_DIR && !filePath.startsWith(`${STORAGE_DIR}${path.sep}`)) {
      return NextResponse.json({ error: 'Invalid file path.' }, { status: 400 });
    }

    const file = await readFile(filePath);

    const extension = path.extname(filename).toLowerCase();
    const contentType = CONTENT_TYPES[extension] || 'application/octet-stream';

    return new NextResponse(file, {
      status: 200,
      headers: {
        'Content-Type': contentType,
        'Cache-Control': 'private, max-age=3600',
      },
    });
  } catch {
    return NextResponse.json({ error: 'File not found.' }, { status: 404 });
  }
}